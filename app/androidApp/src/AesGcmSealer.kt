package com.salahoard.mustnotify

import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * AES-256-GCM envelope: [version byte][12-byte IV][ciphertext + 16-byte tag].
 * Pure JDK code, so it can be unit-tested with a software key; on Android the key comes from the Keystore.
 * [aad] binds a ciphertext to its purpose, so a sealed blob can't be swapped in somewhere else.
 */
class AesGcmSealer(private val key: () -> SecretKey, private val aad: ByteArray) {

    fun seal(plain: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key()) // the IV must be generated by the cipher (the Keystore insists on that)
        cipher.updateAAD(aad)
        val iv = cipher.iv
        check(iv.size == IV_BYTES) { "unexpected IV length" }
        return byteArrayOf(VERSION) + iv + cipher.doFinal(plain)
    }

    /** Throws if the data was tampered with, was sealed with a different key or purpose, or has an unknown format. */
    fun open(sealed: ByteArray): ByteArray {
        require(sealed.size > 1 + IV_BYTES + TAG_BYTES && sealed[0] == VERSION) { "not a sealed blob" }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BYTES * 8, sealed.copyOfRange(1, 1 + IV_BYTES)))
        cipher.updateAAD(aad)
        return cipher.doFinal(sealed, 1 + IV_BYTES, sealed.size - 1 - IV_BYTES)
    }

    private companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val VERSION: Byte = 1
        const val IV_BYTES = 12
        const val TAG_BYTES = 16
    }
}
